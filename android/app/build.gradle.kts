// Secrets and per-developer settings live in local.properties (git-ignored).
// See local.properties.example for the keys this build reads.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun localProp(key: String, default: String): String =
    (localProps.getProperty(key) ?: System.getenv(key.uppercase().replace('.', '_')) ?: default)

